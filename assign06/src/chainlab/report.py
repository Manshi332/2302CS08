"""Generate docs/REPORT.md: header hex dump, branch diagrams, traces, benchmark, acceptance table.

Everything except the timing columns is deterministic, so regenerating the report on another
machine changes only the hash rates and times.
"""

from __future__ import annotations

from typing import Callable, Optional

from .acceptance import run_acceptance
from .bench import format_table, hash_rate, machine_info, run_bench
from .block import hexdump_header
from .simulate import run_fork_simulation, run_work_vs_length


def _fence(text: str, lang: str = "text") -> str:
    return f"```{lang}\n{text}\n```"


def _capture(fn, *args, **kwargs):
    lines: list[str] = []
    result = fn(*args, emit=lines.append, **kwargs)
    return result, "\n".join(lines)


def generate_report(trials: int = 30, bench_bits=(8, 12, 16),
                    log: Optional[Callable[[str], None]] = None) -> str:
    say = log or (lambda _m: None)
    say("running fork simulation ...")
    fork, fork_trace = _capture(run_fork_simulation, 8)
    say("running work-vs-length ...")
    work, work_trace = _capture(run_work_vs_length)
    say("running acceptance checks ...")
    acc_lines: list[str] = []
    acc = run_acceptance(acc_lines.append)
    say("benchmarking ...")
    hps = hash_rate()
    rows = run_bench(bench_bits, trials, log=say)

    a3 = fork["blocks"]["a3"]
    out: list[str] = ["# Assignment 5: Blocks, Proof of Work, Forks and Reorganisation", "",
        "Generated by `python -m chainlab report` (see README). The traces below are produced by the "
        "same code the tests run; block hashes and state hashes are deterministic. Only timings vary "
        "by machine.", "",
        "## 1. Block-header hex dump", "",
        "A real block from the fork simulation (block **A3**, mined at 8 bits, containing one payment "
        "besides the coinbase). The header is a fixed 112-byte structure; the block hash is "
        "`SHA-256(SHA-256(header))`, and the Proof of Work is valid when that digest, read as a "
        "big-endian 256-bit integer, is at most the `target` field.", "",
        _fence(hexdump_header(a3.header)), "",
        "Reading the dump: `version` = 1; `prev_hash` points at block 2; `merkle_root` commits to the "
        "two transaction ids (coinbase + payment); `target` = `2^248 - 1` (8 leading zero bits, so "
        "~256 attempts on average); `nonce` is the value found by the miner. Changing any single bit "
        "of these 112 bytes gives an unrelated hash (avalanche, Assignment 1), which is why a valid "
        "nonce cannot be reused after editing the header.", "",
        "## 2. Diagram of the competing branches", "",
        "Two miners find a block at height 3 at the same time. `*` marks the active chain of "
        "**node A**.", "",
        "**a) Right after the fork is seen (equal cumulative work, first seen stays active):**", "",
        _fence(fork["trees"]["split"]), "",
        "**b) After B4 arrives (branch B has more cumulative work, node A reorganises):**", "",
        _fence(fork["trees"]["resolved"]), "",
        "Mermaid versions of the same trees (green = active chain, red = stale branch):", "",
        _fence(fork["mermaid_split"], "mermaid"), "",
        _fence(fork["mermaid_resolved"], "mermaid"), "",
        "## 3. Fork simulation and resolution (task 6)", "",
        _fence(fork_trace), "",
        "What to notice: while the network is split, node A believes Bob was paid 30 and node B "
        "believes he was not. Neither block is 'wrong'; there is no single-block finality. B4 gives "
        "branch B more cumulative work, so node A disconnects A3 (restoring Alice's spent outputs, "
        "removing Bob's), connects B3 and B4, and hands the orphaned payment back so it can be "
        "mined again (B5). Both nodes then hold the same tip and the same ledger state hash.", "",
        "## 4. Most work, not most blocks (acceptance check 1)", "",
        _fence(work_trace), "",
        "## 5. Hash rate and expected vs observed attempts (task 7)", "",
        f"Machine: {machine_info()}.  Raw SHA-256d header hashing: **{hps:,.0f} hashes/second** "
        "(best of 3 runs of 200,000 hashes).", "",
        f"Each target is mined {trials} times on different fixed pseudo-headers. At `b` bits one attempt "
        "succeeds with probability 2^-b, so attempts are geometrically distributed with mean "
        "(and standard deviation) 2^b. The mean of `n` trials therefore has standard error 2^b/sqrt(n); "
        "`z` is the distance between observed mean and expectation in those units.", "",
        format_table(rows, markdown=True), "",
        "A single search is very noisy (min and max differ by two orders of magnitude, and the median of a "
        "geometric distribution is only about 0.69 x its mean), yet the mean over "
        "trials tracks 2^b, with `z` staying within a few standard errors. Each +4 bits multiplies "
        "the expected work by 16, which the `expected` and time columns reflect.", "",
        "## 6. Acceptance checks", "",
        "| # | check | result | detail |", "|---|---|---|---|"]
    for i, (name, ok, detail) in enumerate(acc, 1):
        out.append(f"| {i} | {name} | {'PASS' if ok else 'FAIL'} | {detail.replace('|', '/')} |")
    out += ["", f"**{sum(1 for _, ok, _ in acc if ok)}/{len(acc)} checks pass.** "
            "Every rejection check also proves the active tip and the full ledger state hash are "
            "unchanged afterwards.", "",
        "## 7. Design notes and limitations", "",
        "* **Chain work** = sum of `floor(2^256 / (target + 1))`. A tie never triggers a reorg, "
        "so the first-seen branch stays active.",
        "* **Targets**: a block may use any target not easier than `pow_limit` (a toy simplification "
        "of retargeting). Harder targets simply count for more work.",
        "* **Side-branch blocks** are fully validated only when their branch becomes active; until "
        "then only PoW, Merkle root, coinbase shape and timestamp are checked. If a branch turns out "
        "to contain an invalid block, the reorganisation is rolled back (check 7) and the offending "
        "block and its descendants are discarded.",
        "* **Atomicity**: `connect_block` applies transactions one by one but undoes them in reverse "
        "if any later rule fails, so a rejected block leaves no trace.",
        "* **Coinbase**: no inputs, memo `coinbase:<height>` (unique txids), value <= subsidy + fees. "
        "Unclaimed value is burned; the ledger invariant is `issued == unspent + burned`. "
        "There is no coinbase maturity rule (real chains need it because reorgs can orphan coinbases).",
        "* **Not modelled**: networking, a mempool (reorgs return transactions to the caller), "
        "difficulty retargeting, SPV proofs. This is a teaching toy, not a cryptocurrency miner.", ""]
    return "\n".join(out)
